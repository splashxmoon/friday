import type { IconName } from "./icons.js";

/**
 * The connector directory, so connecting a service doesn't start with "find the
 * endpoint URL".
 *
 * `auth` is the honest part of this list:
 *  - "none"  connects on one click.
 *  - "token" asks for an API key you paste.
 *  - "oauth" opens the provider's sign-in, then comes back through
 *            /api/mcp/callback. This is what most hosted servers use.
 *
 * Every hosted URL here was probed with a real MCP `initialize` (see
 * `npm run probe:connectors`), and every "oauth" one either registers this app
 * dynamically or is marked `needsClient` because its provider doesn't allow
 * that. Adding a connection probes it again and reports the real status, so an
 * endpoint that has moved shows as an error on its card rather than silently
 * doing nothing. Vendors move these URLs; the error message is the signal.
 */
export interface CatalogEntry {
  id: string;
  name: string;
  mark: IconName;
  blurb: string;
  url: string;
  auth: "none" | "token" | "oauth";
  /**
   * The vendor's own domain, used to show their real favicon as the logo. Served
   * by them, not a third-party logo service, and the SVG mark is the fallback
   * when a vendor blocks hotlinking or has no icon.
   */
  domain?: string;
  /** An explicit logo URL, for vendors whose /favicon.ico isn't an image. */
  logo?: string;
  /** Brands whose mark is black, which disappears on a dark background. */
  invertLogo?: boolean;
  /** What to paste, when a token is needed. */
  tokenHint?: string;
  /** The server answers without a token; one only widens what it will do. */
  tokenOptional?: boolean;
  /**
   * This provider won't register an OAuth client on the fly, so the sign-in
   * only works once someone registers an app by hand and puts its credentials
   * in this server's environment. The value is the key those variables use:
   * `<KEY>_MCP_CLIENT_ID` and `<KEY>_MCP_CLIENT_SECRET`.
   */
  needsClient?: string;
  /** Where to register that app, in one line. */
  clientHint?: string;
  /**
   * This provider only signs in clients whose redirect URI it has approved —
   * in practice its own partner list plus localhost. It connects when Friday
   * runs on your machine and is refused from a hosted URL, which is worth
   * saying on the card rather than at the end of a sign-in.
   */
  localhostOnly?: boolean;
  /**
   * Runs on a machine, not as a hosted service. The default URL is a localhost
   * one, which resolves on the *server* — so it only works when Friday runs on
   * the same machine, and the URL has to be editable for anything else.
   */
  local?: boolean;
  category: Category;
}

